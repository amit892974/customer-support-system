
const pool = require("../config/db");

// AI Tool: Process a refund safely
const process_refund = async (
    orderId,
    reason,
    customerId,
    ticketId,
    idempotencyKey
) => {
    const client = await pool.connect();

    try {
        await client.query("BEGIN");

        // 1. Validate required information
        if (
            !orderId ||
            !Number.isInteger(Number(orderId)) ||
            !reason?.trim() ||
            !ticketId ||
            !idempotencyKey?.trim()
        ) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "Order ID, reason, ticket ID and idempotency key are required."
            };
        }

        // 2. Check whether this request was already submitted
        const duplicate = await client.query(
            `SELECT id, status, amount
             FROM refunds
             WHERE idempotency_key = $1`,
            [idempotencyKey]
        );

        if (duplicate.rows.length > 0) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "This refund request has already been submitted.",
                refund: duplicate.rows[0]
            };
        }

        // 3. Lock and verify the customer's order
        const orderResult = await client.query(
            `SELECT id, customer_id, status, delivery_date, total_amount
             FROM orders
             WHERE id = $1 AND customer_id = $2
             FOR UPDATE`,
            [Number(orderId), customerId]
        );

        if (orderResult.rows.length === 0) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "Order not found."
            };
        }

        const order = orderResult.rows[0];

        // 4. Verify ticket ownership and order association
        const ticketResult = await client.query(
            `SELECT id
             FROM tickets
             WHERE id = $1
               AND customer_id = $2
               AND order_id = $3`,
            [ticketId, customerId, order.id]
        );

        if (ticketResult.rows.length === 0) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "Invalid support ticket for this order."
            };
        }

        // 5. Verify order delivery
        if (order.status !== "delivered" || !order.delivery_date) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "Only delivered orders can be refunded."
            };
        }

        // 6. Check the 30-day demo return window
        const deliveryDate = new Date(order.delivery_date);
        const currentDate = new Date();

        deliveryDate.setUTCHours(0, 0, 0, 0);
        currentDate.setUTCHours(0, 0, 0, 0);

        const daysSinceDelivery = Math.floor(
            (currentDate - deliveryDate) / (1000 * 60 * 60 * 24)
        );

        if (daysSinceDelivery < 0 || daysSinceDelivery > 30) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "The 30-day demo return window has expired."
            };
        }

        // 7. Check existing refund requests for this order
        const existingRefund = await client.query(
            `SELECT id, status
             FROM refunds
             WHERE order_id = $1
               AND status IN ('pending', 'pending_review', 'approved', 'processed')`,
            [order.id]
        );

        if (existingRefund.rows.length > 0) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "A refund request already exists for this order."
            };
        }

        // 8. Calculate refund amount on the backend
        // Never trust an amount generated by the AI or supplied by the client.
        const refundAmount = Number(order.total_amount);

        if (!Number.isFinite(refundAmount) || refundAmount <= 0) {
            await client.query("ROLLBACK");

            return {
                success: false,
                message: "Invalid refundable order amount."
            };
        }

        // 9. Refunds above ₹5,000 require human approval
        const requiresReview = refundAmount > 5000;

        const refundStatus = requiresReview
            ? "pending_review"
            : "processed";

        // 10. Create the simulated refund transaction
        const refundResult = await client.query(
            `INSERT INTO refunds
             (order_id, ticket_id, amount, reason, status,
              requested_by, idempotency_key)
             VALUES ($1, $2, $3, $4, $5, $6, $7)
             RETURNING *`,
            [
                order.id,
                ticketId,
                refundAmount,
                reason.trim(),
                refundStatus,
                customerId,
                idempotencyKey
            ]
        );

        const refund = refundResult.rows[0];

        // 11. Create human escalation when required
        if (requiresReview) {
            await client.query(
                `INSERT INTO escalations
                 (ticket_id, summary, priority, decision)
                 VALUES ($1, $2, $3, $4)`,
                [
                    ticketId,
                    `Refund of INR ${refundAmount} requires human approval. Reason: ${reason.trim()}`,
                    "high",
                    "pending"
                ]
            );
        }

        // 12. Record an audit event
        await client.query(
            `INSERT INTO audit_logs
             (user_id, action, entity_type, entity_id, details)
             VALUES ($1, $2, $3, $4, $5)`,
            [
                customerId,
                requiresReview ? "refund_escalated" : "refund_simulated",
                "refund",
                refund.id,
                JSON.stringify({
                    orderId: order.id,
                    amount: refundAmount,
                    status: refundStatus
                })
            ]
        );

        await client.query("COMMIT");

        return {
            success: true,
            message: requiresReview
                ? "Refund request submitted for human approval."
                : "Simulated refund processed successfully.",
            refund,
            requiresHumanApproval: requiresReview
        };

    } catch (error) {
        await client.query("ROLLBACK");

        console.error("Refund tool error:", error.message);

        return {
            success: false,
            message: "Unable to process refund. Please try again safely."
        };

    } finally {
        client.release();
    }
};

module.exports = {
    process_refund
};
